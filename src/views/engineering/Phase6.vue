        <li><strong>反向推算：</strong>先填目标 TTK，再反推 HP。例如：中型敌机 TTK 目标 4 秒，玩家 DPS 100 → HP = 4 × 100 = 400。你不需要"凭感觉"写一个 HP 数字——<strong>TTK 是你的北极星，所有数字从它推导出来</strong>。</li>
        <li><strong>测试连锁反应：</strong>把攻击力 Lv1 → Lv2 提升 50%（单发伤害从 10 到 15）。观察：所有敌人的 TTK 都缩小了 33%。如果这个变化导致小型敌机从 1.5 秒变成 0.75 秒（几乎瞬间秒杀——失去了"击中"的感觉），你就知道攻击力增长幅度需要调整。这就是数值策划的日常——<strong>不是"写一个数字"，是"管理整个数字网络"</strong>。</li>
        <li><strong>验证极端情况：</strong>模拟"攻击力 Lv1 打 Boss"——TTK 是多少？如果超过 60 秒，玩家会在 Boss 战中途放弃。模拟"攻击力 Lv10 打小怪"——TTK 低于 0.1 秒意味着"还没看到敌人就死了"，清场快感变成了虚无感。这两个极端情况决定了你的数值系统有没有"崩"。</li>
      </ol>
