    <ConceptBlock icon="📖" title="1916 年的数学，今天还在用">
      <p>1916 年，第一次世界大战。英国工程师 Frederick William Lanchester 在前线观察空战——他注意到一个残酷的规律：两架飞机对一架飞机的优势，不是 2:1，而是接近 4:1。他推导出了一个方程：<strong>在战斗中，一支军队的战斗力 = 单位战斗力 × 数量的平方</strong>。这就是"兰彻斯特平方律"。</p>
      <p>100 年后，这个方程成了游戏数值设计的圣经。它解释了一个你直觉上知道但说不清楚的现象：为什么 Boss 的血量不是小怪的 2 倍，而是 20 倍甚至 50 倍？因为如果 Boss 只有 2 倍血量，你打小怪用 1 秒，打 Boss 用 2 秒——这 Boss 毫无"压迫感"。20 倍血量时，你需要持续集中 20 秒——这个过程中任何一次失误都可能致命。<strong>Boss 的血量不是随便定的——它是由"你想让玩家紧张多久"决定的。</strong></p>
      <p>数值设计不是你想象中"数学好的人拿计算器算一算就完了"。它是心理学、数学、游戏设计的交叉点——你的每一个数字都在向玩家发送一个信息："你应该继续玩下去"或者"你应该放弃了"。</p>
    </ConceptBlock>

    <ConceptBlock icon="🔍" title="三个公式统治一切——DPS / EHP / TTK">
      <p>所有战斗系统的数值都可以用三个公式描述：</p>

      <p><strong>DPS（Damage Per Second，每秒伤害）= 单发伤害 × 每秒攻击次数。</strong>如果你的飞机每 0.2 秒发射一发子弹，每发子弹 20 点伤害，DPS = 20 × (1/0.2) = 100。这个数字告诉你"我需要多久才能把敌人的血条削空"。</p>

      <p><strong>EHP（Effective Hit Points，有效生命值）= 血量 ÷ (1 - 免伤率)。</strong>如果敌人有 500 血量，免伤率 20%（护甲减少 20% 伤害），EHP = 500 ÷ (1 - 0.2) = 625。这意味着你需要造成 625 点伤害才能打死它——比纯血量多了 125。这就是为什么有护甲的敌人比纯血量的敌人"更耐打"——即使血量数字看起来一样。</p>

      <p><strong>TTK（Time To Kill，击杀时间）= EHP ÷ DPS。</strong>这是最终极的数字——它告诉玩家"我要对着这个敌人连续射击多久"。以上面的数字为例：TTK = 625 ÷ 100 = 6.25 秒。玩家需要持续射击 6 秒多才能击杀这个敌人。</p>

      <p>这三个公式环环相扣。你改攻击力 → DPS 变 → TTK 变 → 整个战斗节奏变。你改敌人血量 → EHP 变 → TTK 变。你加护甲 → EHP 变 → TTK 变。而<strong>TTK 是玩家最直观感受到的——"这个怪怎么这么肉？"或者"秒杀！爽！"</strong></p>

      <p>这和前端性能优化中"你只改了一个 CSS transform 但影响到了整个合成层"是同样的道理——数值系统的每个变量都是联动的。你不能"只改一个数字"。</p>
    </ConceptBlock>

