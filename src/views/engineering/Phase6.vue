        <li><strong>兰彻斯特方程是游戏数值设计师的"必修公式"：</strong>除了平方律（近战集中火力），还有兰彻斯特线性律（远程分散火力——战斗力 = 单位战斗力 × 数量）。在策略游戏（如《全面战争》系列）中，近战兵种的数值遵循平方律（人越多优势呈指数增长），远程兵种遵循线性律（优势与人数成正比）。理解这个区别，你就理解了为什么 RTS 游戏中"抱团"的近战部队比分散的远程部队更容易滚雪球。</li>
        <li><strong>暴雪的"800% 光环"：</strong>《暗黑破坏神 3》在某个资料片更新时，把一件传奇装备的伤害加成从 100% 调到了 800%。玩家炸锅了——不是因为"太强"，而是因为"数值崩塌"——一旦有了 800% 加成的装备，所有其他装备都失去了意义。游戏数值设计的一条铁律：<strong>不要让一个数字变得比所有其他数字加起来还重要</strong>。这和前端设计中的"不要让一个 CSS !important 覆盖整个样式系统"是一个道理。</li>
