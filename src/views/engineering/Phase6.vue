      <p>你的飞机大战适合<strong>线性 + 阶梯混合</strong>：每波普通波的 TTK 按线性增长（+10%），每第 5 波是 Boss 关——TTK 跳跃式增长（是小怪的 20 倍）。玩家打 4 波小兵热身后进入 Boss 战——心里有节奏预期："打到第 4 波就知道下一波是 Boss 了"。</p>
