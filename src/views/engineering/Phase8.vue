    <ConceptBlock icon="🔍" title="Hook Model——你为什么“戒不掉”？">
      <p>2014 年，Nir Eyal 出版了《Hooked》（中文名《上瘾》），提出了一个解释"为什么人会反复使用一个产品"的模型。他的研究对象包括 Facebook、Instagram、Twitter——但游戏行业发现，这个模型完美解释了<strong>为什么免费游戏比付费游戏更能让人"上瘾"</strong>。</p>

      <p>Hook Model 四个步骤：</p>
      <ol>
        <li><strong>Trigger（触发）——"叮，你的体力回满了"：</strong>外部触发：推送通知、好友邀请、App 图标上的红点。内部触发：无聊了（打开游戏打发时间）、焦虑了（打开游戏放松）。微信小游戏的外部触发天然强——好友分享卡片就是最高效的 Trigger。</li>
        <li><strong>Action（行动）——"点一下就能领 100 金币"：</strong>触发之后的行动必须简单到"不需要思考"。签到领奖是一个点击。每日任务的第一个任务应该是"打开游戏"（自动完成）。<strong>难度门槛每降低 1 步，转化率提升 20%。</strong></li>
        <li><strong>Variable Reward（变化奖励）——"这次掉什么？"：</strong>这是 Hook 的核心。如果签到每天给 100 金币——第 3 天你就没感觉了。但如果签到轮盘随机 50-500 金币——每次都有惊喜。斯金纳箱实验（1950 年代）证明：<strong>随机奖励比固定奖励更能维持行为</strong>。老虎机、抽卡、开宝箱——都是 Variable Reward 的应用。</li>
        <li><strong>Investment（投入）——"我都花了这么多了"：</strong>当玩家投入了时间（肝等级）、金钱（买皮肤）、社交（加了好友），他们很难离开——不是因为"舍不得游戏"，是因为"舍不得已经投入的东西"。这就是沉没成本效应——已经在健身房交了年卡费，不去就是损失。你给好友送了金币——不回送？说不过去。</li>
      </ol>

      <p>整个 Hook Model 转一圈，玩家不知不觉又玩了一个小时。你的飞机大战需要把这个环的每一个节点都设计进去——不是"可选"的，是<strong>必须</strong>的。</p>
    </ConceptBlock>

    <ConceptBlock icon="📊" title="D1/D3/D7/D30——四个时间节点，四种留存策略">
      <p>业界把留存按时间节点分成四个台阶，每个台阶的驱动因素不同：</p>
      <ul>
        <li><strong>D1 留存（次日留存）——靠"新鲜感"：</strong>玩家今天下载了，明天还来吗？驱动因素：新手引导的体验、核心玩法的第一印象。如果你的新手引导流畅且前 3 分钟有"爽感"，D1 做到 40%+ 是可行的。小游戏行业及格线：25%。</li>
        <li><strong>D3 留存（三日留存）——靠"内容深度"：</strong>玩家玩了 3 天，开始摸清系统了。驱动因素：有没有"我还想试试"的新内容（新关卡、新道具、新机制）。如果你的前 3 天内容完全一样——D3 会断崖下跌。</li>
        <li><strong>D7 留存（七日留存）——靠"习惯养成"：</strong>7 天足以形成习惯（心理学"21 天习惯养成"的前 1/3 里程碑）。驱动因素：每日签到循环、每日任务、社交关系。签到 Day 7 要有"大奖励"——让玩家觉得"都签了 6 天了，今天不签就亏了"。</li>
        <li><strong>D30 留存（月留存）——靠"社交 + 养成"：</strong>30 天后留下的玩家是核心用户。驱动因素：社交关系（好友比拼）、深度养成（武器装备、技能树）、排位系统（段位赛季）。D30 做到 10% 以上就是优秀。</li>
      </ul>
      <p>这和 Web 产品的 AARRR 漏斗（Acquisition → Activation → Retention → Revenue → Referral）在逻辑上完全对应——留存（Retention）是漏斗的核心环节。拉新不带来留存就是竹篮打水——你花 10 块钱买一个用户下载，他第二天就走了，这 10 块钱等于扔了。</p>
    </ConceptBlock>

