        <li><strong>3 个每日任务：</strong>① "击杀 50 个敌机"——保证玩家至少玩 1-2 局。② "玩 3 局"——鼓励多玩。③ "使用 1 次道具"——引导玩家尝试道具系统。完成任务进度条在游戏结束时弹出——让玩家看到"还差一个任务就能全领了"。每日 0 点重置。用 <code>wx.setStorageSync('dailyTasks', { ... })</code> 记录进度。</li>
        <li><strong>测试"明天还想玩"：</strong>实现后连续 3 天打开游戏——第 1 天领 100 金币签到了，第 2 天看到 Day2 奖励 150 > Day1 的 100，签到。第 3 天拿到免费复活，去打了一局，把复活用了。到第四天，你打开游戏——看到 Day4 300 金币，签到。如果你在第 5 天没有"今天不签到有点亏"的感觉——说明你的奖励递增幅度还不够大。调整 Day7 的奖励让它有"终极吸引力"——它需要是整个签到循环中价值最高的单项奖励。</li>
        <li><strong>加入 Variable Reward：</strong>把每日任务的奖励从"固定金额"改成"随机范围"——比如"击杀 50 个敌机"奖励 100-300 金币随机。用 <code>Math.floor(Math.random() * 200) + 100</code> 生成。每次看到奖励时的 "这次是 250！上次只有 130！"会让你更期待下一次。</li>
      </ol>
