    <ConceptBlock icon="🔗" title="课外延伸">
      <ul>
        <li><strong>斯金纳箱——1950 年代的实验，今天的游戏设计基石：</strong>B.F. Skinner 把鸽子放进一个箱子里，鸽子每啄一次按钮就掉一粒食物。很快鸽子学会了啄按钮。但真正有意思的是——当他改成"随机间隔"给食物时（有时啄 3 次掉、有时啄 15 次掉），鸽子的啄击频率<strong>暴增</strong>。这就是"间歇性强化"（Intermittent Reinforcement）——不确定的奖励比确定的奖励更能维持行为。你的每日任务随机奖励、抽卡、掉落机制——全部是这个实验的衍生品。Nir Eyal 把斯金纳的理论包装成了 Hook Model 的 Variable Reward 环节。</li>
        <li><strong>Battle Pass 的心理学——为什么"已经买了"让你玩更多：</strong>堡垒之夜 2018 年推出 Battle Pass 时，整个行业都在质疑"让玩家付费买任务？谁会买？"答案是：所有人。Battle Pass 利用了<strong>沉没成本 + 损失厌恶</strong>：你花了 68 元买了战令，如果不在赛季结束前打满等级——你感觉"亏了 68 元"。所以你疯狂打任务。Battle Pass 同时解决了"首次付费"和"长期留存"两个问题——是游戏史上最成功的变现/留存设计之一。这和健身房的"先收费后到店"模式异曲同工——你买了卡，不去就亏。</li>
        <li><strong>推送通知的黄金法则——"让用户觉得有用，不是被骚扰"：</strong>给玩家推"你的好友排名被超越了！"——这是有用信息。推"回来玩吧我们好想你"——这是骚扰。每次推送都在用户的手机通知栏和其他 50 条通知竞争注意力。推得好→打开游戏。推得差→关通知权限（永久失去一个触达渠道）。这和邮件营销的"打开率取决于标题"是同一博弈。</li>
      </ul>
