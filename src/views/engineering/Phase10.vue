      <p>2018 年，Epic Games 在《堡垒之夜》Season 2 推出了 Battle Pass（战斗通行证）：付 950 V-Bucks（约 $9.50），解锁 100 级奖励列表——包括皮肤、舞蹈动作、游戏货币。如果你升满 100 级，拿到的总价值远超 $9.50。</p>
