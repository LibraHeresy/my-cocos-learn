      <p>2013 年，芬兰公司 Supercell 年收入 8.92 亿美元——靠的是两款"免费"游戏：《部落冲突》和《卡通农场》。免费？是的。但他们的变现设计让<strong>玩家主动花钱</strong>，没有人觉得"被宰了"。</p>
