      <p>角色动起来了——但特效呢？引擎火焰、爆炸碎片、受击闪烁——这些不是"附加内容"，它们是玩家<strong>感受</strong>到"我打中了"的媒介。本节做三个特效动画：爆炸、引擎火焰、受击闪烁。</p>
    </ConceptBlock>

    <ConceptBlock icon="💥" title="VFX 设计哲学：每一帧都服务于“感觉”">
      <p>在进入画特效之前，先聊一个底层认知：VFX（Visual Effects，视觉特效）的目的不是"好看"——是<strong>"传达信息"</strong>。每一次攻击命中、每一次爆炸、每一次受伤闪烁——都是在告诉玩家："系统已经检测到这个事件，这是它的视觉反馈。"好的 VFX 让玩家在 50ms 内就知道发生了什么，差的 VFX 让玩家打了两秒后还在想"打中了吗？"</p>
      <p>这和你做前端交互反馈一模一样：按钮点击后的 <code>:active</code> 伪类变暗、表单验证的红色边框、上传文件时的进度条——这些都不是"装饰"，是<strong>系统状态的可视化</strong>。VFX 就是游戏世界的"微交互"。</p>
      <p>一个经验法则：<strong>玩家能感知的最小时间窗口约 50-100ms</strong>。所以特效的关键帧（爆发帧、命中帧）必须在这个时间窗口内出现——否则反馈就会有"延迟感"。这不是技术限制，是人体生理限制。</p>
    </ConceptBlock>

    <ConceptBlock icon="🎆" title="三种特效的结构拆解">
      <h3>爆炸特效：冲击 → 膨胀 → 消散</h3>
      <p>爆炸是典型的一次性动画，有清晰的"剧情弧线"：</p>
      <ul>
        <li><strong>帧 1（起爆）：</strong> 爆炸中心出现一个 3×3 的亮白色/亮黄色小圆或菱形。这是"能量核心"——面积小、颜色极亮。玩家在这一帧感知到"有什么东西炸了"。</li>
        <li><strong>帧 2（膨胀）：</strong> 光线向外扩张——面积变大约 1.5-2 倍，颜色从白/黄变为橙色。轮廓变成不规则的星形或多边形（不要画成完美的圆——真实的爆炸是破碎的）。</li>
        <li><strong>帧 3（峰值 + 碎片）：</strong> 面积继续扩张，颜色从橙变红。外围出现 3-5 个分离的碎片（2-4px 大小的小色块），向外飞散。</li>
        <li><strong>帧 4（暗红余烬）：</strong> 中心变暗（深红/棕），碎片向外移动+缩小。</li>
        <li><strong>帧 5（烟雾）：</strong> 暗灰色烟雾代替火焰，碎片继续变小或消失。</li>
        <li><strong>帧 6（消散）：</strong> 烟雾变淡，接近透明/背景色。</li>
      </ul>
      <p>帧率建议：每帧 80-100ms。6 帧爆炸约 0.5-0.6 秒——刚好够玩家看清"爆炸了 → 炸完了"的过程。更快的节奏（4 帧=0.3 秒）会更"干练"，适合小型敌机的快速爆炸。</p>

      <h3>引擎火焰：4 帧循环的永动机</h3>
      <p>引擎火焰是循环动画，所以它的设计核心是<strong>"形态在变，位置不变"</strong>：</p>
      <ul>
        <li>火焰的底部固定在引擎喷口——无论火焰形态怎么变，根部不动。</li>
        <li>火焰的颜色从底部向上渐变：白（最热，根部）→ 黄 → 橙 → 红（最冷，顶部尖端）。在像素画中用 3 层颜色的垂直渐变表达。</li>
        <li>4 帧的设计：帧 1 火焰最长（3-4px）+ 尖端圆钝；帧 2 火焰中等（2-3px）+ 尖端分叉（变成两个小叉）；帧 3 火焰最短（1-2px）+ 扁平；帧 4 火焰中等+尖端圆钝。4 帧循环，每帧 100ms。</li>
      </ul>
      <p>核心原理：火焰的形态变化是<strong>周期性</strong>的——不一定是严格的物理模拟，只要形态有一个"长→短→长"的周期，肉眼就会解读为"在燃烧"。</p>

      <h3>受击闪烁：最简单的 2 帧 VFX</h3>
      <p>敌机被子弹命中——瞬间变成全白色（或者叠加一个白色半透明图层），然后变回正常。这就是受击闪烁。</p>
      <ul>
        <li><strong>帧 1（白闪）：</strong> 角色的所有颜色像素替换为白色（或叠加白色）。持续时间：50-80ms（极短）。</li>
        <li><strong>帧 2（恢复）：</strong> 恢复正常颜色。如果想让"受击感"更强——用 3 帧：白闪（50ms）→ 正常（50ms）→ 白闪（50ms）→ 正常。这种"闪两次"比单次更显眼。</li>
      </ul>
      <p>受击闪烁的信息价值极高——它是玩家判断"我打中了"的唯一视觉信号。没有它，玩家只能靠血条下降来判断——而血条需要视线移动到屏幕角落，这 0.3 秒的视线偏移在激烈的弹幕战中就是生和死的距离。受击闪烁让反馈出现在<strong>玩家视线聚焦的区域</strong>（你正在看敌机），不需要移动视线。</p>
    </ConceptBlock>

    <ConceptBlock icon="🔧" title="动手：三个特效全做出来">
      <p>打开 Aseprite。这次我们直接做三个独立的小文件——每个特效一个文件，方便导出为独立的 SpriteSheet。</p>

      <h3>爆炸特效（32×32，6 帧）</h3>
      <ol>
        <li>新建 32×32 画布，背景透明。</li>
        <li>新建 6 帧（时间轴 → New Frame × 6）。</li>
        <li>帧 1：画布中央画 3×3 白/黄色菱形。</li>
        <li>帧 2：用橙色扩展成不规则的 5×5 多边形。</li>
        <li>帧 3：红色再扩展+外围加 3-4 个分离的碎片（2px 大小，黄色，散在四周）。</li>
        <li>帧 4：中心变深红/棕色，碎片向外移 2px 并缩小。</li>
        <li>帧 5：中心变暗灰，碎片消失或变成 1px 小点。</li>
        <li>帧 6：几乎消散——残留 1-2 个暗灰像素。</li>
        <li>每帧 Duration = 80ms，Loop 模式 = 不循环（播完一次停止）。</li>
        <li>导出：File → Export Sprite Sheet → 保存为 <code>explosion.png</code>。</li>
      </ol>

      <h3>引擎火焰（16×8，4 帧）</h3>
      <ol>
        <li>新建 16×8 画布，背景透明。</li>
        <li>帧 1：从底部（喷口处）向上画 3×4 像素的火焰，颜色：底白→中黄→顶橙。火焰尖端圆钝。</li>
        <li>帧 2：火焰稍短（2×3），尖端分成两个小叉（2 条分开的 1px 线）。</li>
        <li>帧 3：火焰更短（1×2），扁平——像被压缩了。</li>
        <li>帧 4：火焰恢复到中等长度（2×3），尖端圆钝。</li>
        <li>Per-frame Duration = 100ms。Loop 模式 = 循环。</li>
        <li>导出为 <code>engine_flame.png</code>。</li>
      </ol>

      <h3>受击闪烁（复用敌机角色，2 帧）</h3>
      <ol>
        <li>打开你的敌机角色 .aseprite 文件。</li>
        <li>新建一个图层叫 "hit_flash"。</li>
        <li>在时间轴新建 2 帧。</li>
        <li>帧 1（正常）：敌机正常颜色。</li>
        <li>帧 2（白闪）：在 hit_flash 图层上，用白色填充敌机的所有区域。可以快速做：复制敌机的像素到 hit_flash 图层，然后用颜色替换（Edit → Replace Color：选任意原色 → 替换为白色）。</li>
        <li>帧 Duration：帧 1=50ms，帧 2=50ms。不循环。</li>
        <li>在游戏中，受击闪烁的逻辑是代码控制的（hit → 切换到白闪帧 → 50ms 后切回正常帧）。你不需要做"循环闪烁"——代码会处理触发时机。</li>
      </ol>
    </ConceptBlock>

    <ConceptBlock icon="🔗" title="课外延伸">
      <ul>
        <li><strong>VFX Artist——游戏行业最"值钱"的职位之一：</strong> 在 AAA 游戏团队里，VFX Artist 的职责是让每一下攻击、每一次爆炸、每一个法术"有感觉"。《哈迪斯》（Hades）的 VFX 团队为每一个技能做 20-40 帧的手绘序列——你看到的每一次地狱火焰喷发、每一次宙斯闪电链，背后都有几十帧逐帧绘制。这不是渲染引擎算出来的——是画师一张张画出来的。这就是为什么《哈迪斯》的"手感"在 Roguelike 游戏中被称为天花板。好的 VFX 不只是"好看"——它在物理层面影响玩家对游戏的反应速度。</li>
        <li><strong>2D 粒子系统——VFX 的工业化方案：</strong> 手绘爆炸序列适合"固定形状"的特效（比如一个固定大小的爆炸），但当你有 100 颗子弹需要各自独立的微小火花时——画 100 个不同的 SpriteSheet 不现实。这时候用粒子系统（Cocos 的 ParticleSystem2D）：用 1-3 个基础像素粒子贴图（2-4px 小方块），靠发射器参数（方向/速度/生命周期/颜色渐变）生成无数种变化。Phase 20 会详细讲粒子系统——但你现在就可以在脑中建立这个概念：<strong>逐帧动画 = 手绘的确定性；粒子系统 = 参数驱动的随机性</strong>。两者不是替代关系——是互补关系。</li>
        <li><strong>引擎火焰的物理真相——比你想象的复杂：</strong> 引擎火焰不是"一团火"——它是燃烧产物（气体）在喷口高速喷出后和大气摩擦产生的发光现象。火焰的形态取决于喷气速度和方向：匀速时火焰稳定，加速时火焰拉长，转向时火焰弯曲。理解了这一点，你就能做出"加速时火焰拉长"和"转向时火焰偏折"的细节——这些细节是区分"随便画的火焰"和"让人相信的火焰"的关键。</li>
      </ul>
